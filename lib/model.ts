// Token Radar's model, radar-2: one snapshot of the protocol universe in,
// one ranked board out.
//
// The board covers every slug in the snapshot's watchlist (the floor, never
// a ceiling) and adds every pre-token protocol below the floor that the field
// guide still allows: no token recorded, not a wrapped, staked or bridged
// product of a token that trades, not an exchange, not a versioned pool.
// A protocol is pre-token when its record carries no token (no market cap,
// no CoinGecko id, no symbol); the snapshot's live-token protocols are kept
// apart and shown as the market's own values, never mixed into the board.
//
// Implied value follows only from the snapshot's own figures:
//
//   base       = tvl_usd x CATEGORY_MULTIPLE[category]
//   growth     = clamp(change_7d, -60, 120) per cent
//   growthMult = 1 + (growth / 100) x GROWTH_WEIGHT
//   maturity   = 0.6 + min(age_days, 1095) / 1095 x 0.4   (age unknown: 365)
//   chainMult  = 1 + min(chains - 1, 4) x 0.03
//   implied    = max(1, round(base x growthMult x maturity x chainMult))
//
// The category multiples are sector priors, stated in full on the dashboard:
// fee-earning venues (DEX, derivatives, prediction) price higher against
// TVL than asset-backed or yield products (RWA, basis trading, stablecoin
// wrappers), chains highest of all because a chain token prices a whole
// economy rather than one app. No protocol name is ever special-cased: the
// same function scores every row, and the dashboard recomputes every row
// from the same constants so the page and the board can never disagree.

/** The snapshot's protocol entry: exactly the ten fields the sealed input carries. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

